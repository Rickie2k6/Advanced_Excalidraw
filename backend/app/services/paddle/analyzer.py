from datetime import (
    datetime,
    timezone,
)
from threading import Lock

import numpy as np
from PIL import Image

from app.core.config import settings

from app.services.paddle.model import (
    get_pipeline,
)

from app.services.paddle.parser import (
    extract_direct_formula,
    extract_formula_blocks,
)


_inference_lock = Lock()


def analyze_whiteboard(
    image: Image.Image,
):
    """
    EN:
    Analyze one complete whiteboard image using
    PaddleOCR-VL layout detection.

    This is the original analysis flow and is kept
    for debugging and comparison.

    VI:
    Phân tích toàn bộ một ảnh whiteboard bằng
    PaddleOCR-VL layout detection.

    Đây là flow phân tích ban đầu và được giữ lại
    để debug và so sánh kết quả.
    """
    pipeline = get_pipeline()

    image = image.convert(
        "RGB"
    )

    image_array = np.asarray(
        image
    )

    with _inference_lock:
        output = pipeline.predict(
            image_array,

            use_doc_orientation_classify=False,

            use_doc_unwarping=False,

            use_layout_detection=True,

            use_chart_recognition=False,

            use_seal_recognition=False,

            use_ocr_for_image_block=False,

            format_block_content=False,

            layout_shape_mode="rect",

            layout_threshold=(
                settings
                .paddle_layout_threshold
            ),

            merge_layout_blocks=False,

            use_queues=False,
        )

        pages = list(output)

    if not pages:
        raise RuntimeError(
            "PaddleOCR returned "
            "no result."
        )

    print(
        "\n========== "
        "RAW PADDLE OUTPUT "
        "=========="
    )

    for i, page in enumerate(
        pages
    ):
        print(
            f"\n----- PAGE "
            f"{i + 1} -----"
        )

        page.print()

    print(
        "===================="
        "===================\n"
    )

    detected_formulas = []

    all_labels = []

    all_block_count = 0

    for page in pages:
        (
            formulas,
            labels,
            block_count,
        ) = extract_formula_blocks(
            page
        )

        detected_formulas.extend(
            formulas
        )

        all_labels.extend(
            labels
        )

        all_block_count += (
            block_count
        )

    boxes = []

    for index, formula in enumerate(
        detected_formulas,
        start=1,
    ):
        boxes.append({
            "id": index,

            "label":
                formula["label"],

            "bbox":
                formula["bbox"],

            "equation":
                formula["equation"],

            "block_id":
                formula["block_id"],

            "block_order":
                formula[
                    "block_order"
                ],
        })

    return {
        "timestamp":
            datetime.now(
                timezone.utc
            ).isoformat(),

        "image_width":
            image.width,

        "image_height":
            image.height,

        "box_count":
            len(boxes),

        "boxes":
            boxes,

        "all_block_count":
            all_block_count,

        "all_block_labels":
            all_labels,
    }


def analyze_equation_images(
    images: list[Image.Image],
    boxes_meta: list[dict],
):
    """
    EN:
    Recognize equations from multiple equation crops
    generated by Excalidraw.

    Excalidraw already determines the equation boxes,
    so Paddle layout detection is disabled. PaddleOCR-VL
    is used only for formula recognition.

    VI:
    Nhận dạng các phương trình từ nhiều ảnh crop
    equation được tạo bởi Excalidraw.

    Vì Excalidraw đã xác định các equation box,
    Paddle layout detection sẽ được tắt. PaddleOCR-VL
    chỉ được sử dụng để nhận dạng công thức.
    """
    if not images:
        raise ValueError(
            "No equation images "
            "were provided."
        )

    if len(images) != len(
        boxes_meta
    ):
        raise ValueError(
            "Number of equation images "
            "does not match number "
            "of equation boxes."
        )

    pipeline = get_pipeline()

    image_arrays = []

    normalized_images = []

    for image in images:
        rgb_image = image.convert(
            "RGB"
        )

        normalized_images.append(
            rgb_image
        )

        image_arrays.append(
            np.asarray(
                rgb_image
            )
        )

    with _inference_lock:
        output = pipeline.predict(
            image_arrays,

            use_doc_orientation_classify=False,

            use_doc_unwarping=False,

            # Excalidraw already detected
            # each equation region.
            use_layout_detection=False,

            # Each crop contains exactly
            # one mathematical formula.
            prompt_label="formula",

            use_chart_recognition=False,

            use_seal_recognition=False,

            use_ocr_for_image_block=False,

            format_block_content=False,

            use_queues=False,
        )

        results = list(output)

    if not results:
        raise RuntimeError(
            "PaddleOCR returned "
            "no equation results."
        )

    if len(results) != len(
        normalized_images
    ):
        raise RuntimeError(
            "PaddleOCR result count "
            "does not match equation "
            "image count."
        )

    print(
        "\n========== "
        "RAW EQUATION OUTPUT "
        "=========="
    )

    for index, result in enumerate(
        results,
        start=1,
    ):
        print(
            f"\n----- EQUATION "
            f"{index} -----"
        )

        result.print()

    print(
        "======================"
        "=================\n"
    )

    boxes = []

    for index, (
        result,
        image,
        metadata,
    ) in enumerate(
        zip(
            results,
            normalized_images,
            boxes_meta,
        ),
        start=1,
    ):
        equation = (
            extract_direct_formula(
                result
            )
        )

        bbox = metadata.get(
            "bbox",
            [],
        )

        box_id = metadata.get(
            "id",
            index,
        )

        boxes.append({
            "id":
                int(box_id),

            "label":
                "display_formula",

            # This bbox comes from
            # Excalidraw scene coordinates.
            "bbox": [
                float(value)
                for value in bbox
            ],

            "equation":
                equation,

            "block_id":
                index - 1,

            "block_order":
                index,
        })

        print(
            f"[Equation Box {box_id}] "
            f"{image.width}x{image.height} "
            f"-> {equation}"
        )

    print(
        "\nPaddleOCR recognized "
        f"{len(boxes)} equation boxes."
    )

    for box in boxes:
        print(
            f"Box {box['id']}: "
            f"{box['equation']}"
        )

    return {
        "timestamp":
            datetime.now(
                timezone.utc
            ).isoformat(),

        # There is no single full image in
        # this flow because each equation
        # is sent as an individual crop.
        "image_width":
            None,

        "image_height":
            None,

        "box_count":
            len(boxes),

        "boxes":
            boxes,

        "all_block_count":
            len(boxes),

        "all_block_labels": [
            "display_formula"
            for _ in boxes
        ],
    }