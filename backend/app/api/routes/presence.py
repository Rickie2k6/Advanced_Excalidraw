from __future__ import annotations

from uuid import UUID

from fastapi import (
    APIRouter,
    Request,
)

from app.services.room_presence import (
    get_presence_status,
    heartbeat_session,
    join_session,
    leave_session,
)


router = APIRouter()


# ============================================================
# CLIENT IP
# ============================================================


def get_client_ip(
    request: Request,
) -> str | None:
    """
    Resolve the public IP of the browser making
    the request.

    Priority:
    1. Cloudflare's CF-Connecting-IP
    2. X-Forwarded-For
    3. Direct socket client address

    The same public IP is used for identifying
    stroke/equation contributors.
    """

    # --------------------------------------------------------
    # 1. Cloudflare Tunnel
    # --------------------------------------------------------

    cloudflare_ip = (
        request.headers.get(
            "cf-connecting-ip"
        )
    )

    if cloudflare_ip:
        return cloudflare_ip.strip()


    # --------------------------------------------------------
    # 2. Reverse proxy fallback
    # --------------------------------------------------------

    forwarded_for = (
        request.headers.get(
            "x-forwarded-for"
        )
    )

    if forwarded_for:

        # X-Forwarded-For may look like:
        #
        # client, proxy1, proxy2
        #
        # The first IP is the original client.
        first_ip = (
            forwarded_for
            .split(",")[0]
            .strip()
        )

        if first_ip:
            return first_ip


    # --------------------------------------------------------
    # 3. Direct connection fallback
    # --------------------------------------------------------

    if request.client:
        return request.client.host

    return None


# ============================================================
# JOIN ROOM
# ============================================================


@router.post(
    "/presence/join"
)
async def presence_join(
    request: Request,
    session_id: UUID,
):
    """
    Register a browser/tab as an active room session.

    session_id is generated by the frontend.

    Example:

    POST /api/presence/join
         ?session_id=<uuid>
    """

    client_ip = (
        get_client_ip(
            request
        )
    )

    result = await join_session(
        session_id=str(
            session_id
        ),
        client_ip=client_ip,
    )

    return result


# ============================================================
# HEARTBEAT
# ============================================================


@router.post(
    "/presence/heartbeat"
)
async def presence_heartbeat(
    request: Request,
    session_id: UUID,
):
    """
    Tell the backend that this browser/tab is
    still active.

    The frontend will call this periodically.
    """

    client_ip = (
        get_client_ip(
            request
        )
    )

    result = await heartbeat_session(
        session_id=str(
            session_id
        ),
        client_ip=client_ip,
    )

    return result


# ============================================================
# LEAVE ROOM
# ============================================================


@router.post(
    "/presence/leave"
)
async def presence_leave(
    session_id: UUID,
):
    """
    Remove a browser/tab from the room.

    If this is the final active session,
    room_presence.py resets:

    - strokes.json
    - equations.json
    """

    result = await leave_session(
        session_id=str(
            session_id
        )
    )

    return result


# ============================================================
# STATUS / DEBUG
# ============================================================


@router.get(
    "/presence/status"
)
async def presence_status():
    """
    Development endpoint for checking who is
    currently considered active in the room.
    """

    return await get_presence_status()